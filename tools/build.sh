#!/usr/bin/env bash
# usage: tools/build.sh [--wipe] [--release] [--sanitize | --no-xwayland] [build-dir]
#
# Configure and compile the compositor: the one command a clean checkout
# needs. Takes meson and ninja from PATH when they run there, else from the
# repo's .venv (tools/venv.sh), configures through toolchain/llvm.ini and sets
# the build dir up again when it was configured with another compiler or was
# not set up by meson for this checkout. --sanitize builds build-asan/ with
# AddressSanitizer and UndefinedBehaviorSanitizer, wlroots included.
# --no-xwayland builds build-no-xwayland/ with wlroots' Xwayland support off,
# the build of a machine whose wlroots lacks it.
# tools/check.sh and tools/package.sh build through this.
set -euo pipefail
. "$(dirname -- "${BASH_SOURCE[0]}")/lib.sh"

repo=$(repo_root)
cd "$repo"

wipe=0
sanitize=0
no_xwayland=0
options=()
build=
while [ $# -gt 0 ]; do
	case $1 in
		--wipe) wipe=1 ;;
		--release) options+=(-Dbuildtype=release) ;;
		--sanitize) sanitize=1 ;;
		--no-xwayland) no_xwayland=1 ;;
		-h | --help)
			usage_from_header
			exit 0
			;;
		-*) die "unknown argument: $1 (try --help)" ;;
		*) build=$1 ;;
	esac
	shift
done

if [ "$sanitize" -eq 1 ] && [ "$no_xwayland" -eq 1 ]; then
	die "--sanitize and --no-xwayland are separate builds"
fi
if [ "$sanitize" -eq 1 ]; then
	# b_lundef=false: the sanitizer runtimes resolve at load time, which the
	# linker's default --no-undefined refuses
	options+=(-Db_sanitize=address,undefined -Db_lundef=false)
	build=${build:-build-asan}
fi
if [ "$no_xwayland" -eq 1 ]; then
	options+=(-Dwlroots:xwayland=disabled)
	build=${build:-build-no-xwayland}
fi
build=${build:-build}

use_venv
if [ -n "$venv_bin" ]; then
	echo "build.sh: using $venv_bin meson/ninja"
fi

# A build dir counts only when meson set it up for this checkout: one made by
# a checkout at another path keeps that path in every command, and one half
# deleted (rm -rf build/* keeps its dotfiles) is no build dir at all.
set_up_here() {
	[ -f "$build/meson-private/coredata.dat" ] &&
		[ "$(sed -n 's/.*"source": "\([^"]*\)".*/\1/p' "$build/meson-info/meson-info.json" 2>/dev/null)" = "$repo" ]
}
if [ -d "$build" ] && ! set_up_here; then
	grep -qs 'autogenerated by Meson' "$build/.gitignore" ||
		die "$build/ is not a meson build dir; leaving it alone"
	echo "build.sh: $build/ was not set up by meson for this checkout; removing it"
	rm -rf "$build"
fi

native=(--native-file toolchain/llvm.ini)
if [ ! -d "$build" ]; then
	echo "build.sh: meson setup $build ${native[*]} ${options[*]}"
	meson setup "$build" "${native[@]}" "${options[@]}"
elif [ "$wipe" -eq 1 ]; then
	echo "build.sh: meson setup --wipe $build ${native[*]} ${options[*]}"
	meson setup --wipe "$build" "${native[@]}" "${options[@]}"
elif set_up_by=$(sed -n 's/.*"meson_version": {"full": "\([^"]*\)".*/\1/p' "$build/meson-info/meson-info.json") &&
		[ "$set_up_by" != "$(meson --version)" ]; then
	# the venv takes the latest meson, and meson loads no build dir another
	# version set up until it is reconfigured
	echo "build.sh: $build/ was set up by meson $set_up_by; meson setup --reconfigure"
	meson setup --reconfigure "$build" "${options[@]}"
elif meson introspect "$build" --compilers 2>/dev/null | grep -q '"id": "gcc"'; then
	echo "build.sh: $build/ was configured with GCC; meson setup --wipe"
	meson setup --wipe "$build" "${native[@]}" "${options[@]}"
elif [ "${#options[@]}" -gt 0 ]; then
	meson configure "$build" "${options[@]}"
fi

echo "build.sh: meson compile -C $build"
meson compile -C "$build"
echo "build.sh: $build/wayland-canvas"
